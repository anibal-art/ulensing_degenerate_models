#!/usr/bin/env python3

"""
Audit the aggregated Gate-1 H0 optimizer-diagnostics table.

PURPOSE
    `gate1_oracle_diagnostics.csv` (produced by
    `aggregate_gate1_oracle_diagnostics.py`) combines three distinct
    local Gate-1 runs into one table. Before that table is used as
    input to any adaptive-H0 analysis, this script verifies that the
    three runs are unambiguously distinguishable and internally
    consistent, and reports the structural facts an analyst needs
    before trusting the table:

    - final columns and row counts per `source` (run);
    - number of events and semantic strategies per `source`, using
      BOTH the raw (mode, label) pair and the canonical
      (mode, strategy_id) pair;
    - whether the (mode, start_slot) -> label mapping is constant
      across events within each `source` (verified empirically, not
      assumed), and separately whether every (mode, strategy_id) pair
      covers all events in that source (i.e. strategy_id is a total,
      consistent key);
    - duplicate or missing (mode, catalog_row, start_slot) /
      (mode, catalog_row, label) / (mode, catalog_row, strategy_id)
      keys per `source`;
    - distribution of `optimizer_success` and `optimizer_active_mask`,
      reported SEPARATELY as:
        * per_fit_*   -- over every individual H0 optimization
                         (one row = one start);
        * winner_*    -- over only the per-(source, catalog_row)
                         minimum-chi2 row (i.e. one row per event,
                         the start that "wins" for that event within
                         that source/run).
      These two views answer different questions: per_fit_* describes
      how often an individual start lands on a bound; winner_*
      describes how often the SELECTED solution for an event does.
      A high per_fit_rho_active_rate does not by itself imply the
      rho domain is insufficient (see interpretation notes in
      ADAPTIVE_H0_ANALYSIS.md) -- that question is about winners, not
      individual starts.
    - a hard integrity check per `source`: `hypothesis` is `"H0"`
      everywhere, `status` is `"success"` everywhere usable rows are
      expected to be usable, `chi2`/`t0`/`u0`/`tE`/`rho` are finite on
      every `status=="success"` row, `h0_start_plan` and
      `t0_margin_factor` match the run's own declared values with no
      exceptions, and the set of `catalog_row` values is exactly the
      100-event `extreme100` reference set (no extra, none missing).
      THIS CHECK RAISES `RuntimeError` on any violation -- it is not
      print-only, because a silent structural violation here would
      corrupt every downstream Phase A/B result built on this table.

INPUTS
    validation/bounds_convergence/results/gate1_oracle_diagnostics.csv
        (produced by aggregate_gate1_oracle_diagnostics.py; not
        regenerated by this script)

OUTPUTS
    validation/bounds_convergence/results/
        gate1_oracle_diagnostics_audit_by_source.csv
            one row per `source`: row/event/strategy counts (raw
            label and canonical strategy_id), the hard integrity
            check's counters (hypothesis/status/finiteness/
            h0_start_plan/t0_margin_factor/catalog_row-set), the same
            duplicate/missing counts, start_slot/strategy_id
            consistency flags, and per_fit_* / winner_* optimizer
            diagnostics.
        gate1_oracle_diagnostics_audit_start_slot_map.csv
            one row per (source, mode, start_slot): the set of
            distinct labels observed at that slot across events,
            and whether that set has size 1 (i.e. the slot is
            label-stable for that source/mode).
        gate1_oracle_diagnostics_audit_strategy_id_coverage.csv
            one row per (source, mode, strategy_id): how many
            distinct events that strategy_id appears for in that
            source, and whether that equals the source's total event
            count (i.e. strategy_id is present for every event, never
            silently dropped for some).

WHAT QUESTION THIS ANSWERS
    "Is gate1_oracle_diagnostics.csv structurally sound, and can
    (mode, strategy_id) be trusted as a strategy key that is stable
    across events, separately for each of the three source runs?"

ORACLE USAGE
    None. This is a pure data-integrity audit; it does not compare
    any run against another run's chi2, and does not use any
    oracle/validation-only information. The winner_* statistics use
    only the MINIMUM CHI2 WITHIN THE SAME SOURCE/RUN (i.e. the best
    of that run's own starts for that event) -- this is not the
    52-fit or 5-fit oracle from another source, and is not compared
    against it here.

STATUS
    Development / documentation tooling. Not a scientific validation
    result. Referenced from ADAPTIVE_H0_ANALYSIS.md, Phase 0
    (table audit), which precedes the Phase A/B adaptive analysis.
"""

