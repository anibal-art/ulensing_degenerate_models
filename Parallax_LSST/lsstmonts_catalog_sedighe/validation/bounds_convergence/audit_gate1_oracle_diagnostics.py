def _parse_active_mask(raw) -> tuple[int, ...] | None:

    if not isinstance(raw, str):
        return None

    try:
        val = ast.literal_eval(raw)
    except (ValueError, SyntaxError):
        return None

    return tuple(int(x) for x in val)


